#!/usr/bin/env python3
"""
s05_avl.py -- generate the AVL geometry/mass files for the optimised BWB, drive AVL, size fins + elevons.

Stages
  A  write beluga.avl / beluga.mass from results/design.json + results/mass_props.json
  B  re-trim the washout *with AVL* (elevons neutral at cruise CL)  [AVL is the authority, s03's VLM is a screen]
  C  sweep wingtip-fin height x elevon chord fraction:  Cn_beta, Cl_beta, spiral criterion, Cm_delta, trim at slow flight
  D  final run -> results/avl/final_st.txt + final_ft.txt + avl_results.json   (consumed by s06_state_space.py)

Usage:  python3 s05_avl.py            full run (needs the avl binary)
        python3 s05_avl.py --dry      only write the input files
AVL axes: x aft, y right, z up.  Positive control = trailing edge down.
"""
import os, sys, re, json, shutil, subprocess
import numpy as np
import config as C

AVLDIR = os.path.join(C.RES, "avl")
os.makedirs(AVLDIR, exist_ok=True)
NUM = r"[-+]?(?:\d+\.?\d*|\.\d+)(?:[EeDd][-+]?\d+)?"


# ------------------------------------------------------------------ file writers
def _interp(st, key, y):
    return float(np.interp(y, st["y"], st[key]))


def avl_text(D, mp, fin_h, el_frac, twist_tip):
    st = D["stations"]
    s = D["planform"]["span"] / 2
    yk = st["y"][1]
    y_in = D["elevon"]["y_in_frac"] * s
    ys = sorted({0.0, yk, y_in, s})
    ys = [y for i, y in enumerate(ys) if i == 0 or y - ys[i - 1] > 0.004]
    cg = mp["cg"]
    L = []
    L += ["Flying Beluga BWB (generated by s05_avl.py)", "0.0                    !Mach",
          "0   0   0.0            !iYsym  iZsym  Zsym",
          f"{D['S']:.6f} {D['MAC']:.6f} {D['planform']['span']:.6f}   !Sref Cref Bref",
          f"{cg[0]:.5f} 0.0 {cg[2]:.5f}      !Xref Yref Zref  (= CG)", "0.0                    !CDp", ""]
    L += ["#=====================================================", "SURFACE", "Wing", "10 1.0 12 1.0", "YDUPLICATE", "0.0", "", ""]
    for y in ys:
        shape = np.interp(y, [0, yk, s], [0, 0, 1])
        has_ctl = y >= y_in - 1e-6
        L += ["SECTION", f"{_interp(st,'xle',y):.5f} {y:.5f} 0.0 {_interp(st,'chord',y):.5f} {twist_tip*shape:.4f}  8 1.0",
              "AFILE", "af.dat"]
        if has_ctl:
            xh = 1.0 - el_frac
            L += ["CONTROL", f"elevator 1.0 {xh:.3f}  0.0 0.0 0.0  1.0", "CONTROL", f"aileron  1.0 {xh:.3f}  0.0 0.0 0.0 -1.0"]
        L += [""]
    # fixed vertical wingtip fins
    xt, ct = _interp(st, "xle", s), _interp(st, "chord", s)
    L += ["#=====================================================", "SURFACE", "Fin", "6 1.0 6 1.0", "YDUPLICATE", "0.0", "", "",
          "SECTION", f"{xt:.5f} {s:.5f} 0.0 {ct:.5f} 0.0", "NACA", "0008", "",
          "SECTION", f"{xt+fin_h*np.tan(np.radians(C.FIN_SWEEP_DEG)):.5f} {s:.5f} {fin_h:.5f} {ct*C.FIN_TAPER:.5f} 0.0", "NACA", "0008", ""]
    return "\n".join(L) + "\n"


def mass_text(mp, D):
    return "\n".join(["Lunit = 1.0 m", "Munit = 1.0 kg", "Tunit = 1.0 s", f"g = {C.G}", f"rho = {C.RHO}", "",
                      "#  mass     x       y      z       Ixx       Iyy       Izz       Ixy  Ixz       Iyz",
                      f"   {mp['mass']:.5f} {mp['cg'][0]:.5f} 0.0 {mp['cg'][2]:.5f} {mp['Ixx']:.6f} {mp['Iyy']:.6f} {mp['Izz']:.6f} 0.0 {mp['Ixz']:.7f} 0.0", ""])


# ------------------------------------------------------------------ AVL driver
def parse(path):
    d = {}
    if not os.path.exists(path):
        return d
    for ln in open(path, errors="ignore"):
        for k, v in re.findall(r"([A-Za-z][A-Za-z0-9']*)\s*=\s*(" + NUM + ")", ln):
            try:
                d[k] = float(v.replace("D", "E").replace("d", "e"))
            except ValueError:
                pass
    return d


def avl_run(avlfile, setup, tag, extra_ft_only=False):
    """setup: list of OPER-menu commands (e.g. ['a c 0.3','d1 pm 0']). returns merged dict of FT + ST outputs"""
    exe = shutil.which(C.AVL_BIN)
    if exe is None:
        raise RuntimeError("avl binary not found. See README (build AVL 3.36) or set AVL_BIN=/path/to/avl")
    for f in (f"{tag}_st.txt", f"{tag}_ft.txt"):
        p = os.path.join(AVLDIR, f)
        if os.path.exists(p):
            os.remove(p)
    cmds = ["plop", "g", "", f"load {avlfile}", "oper"] + setup + ["x", "st", f"{tag}_st.txt", "ft", f"{tag}_ft.txt", "", "", "quit"]
    runner = [shutil.which("xvfb-run"), "-a", exe] if shutil.which("xvfb-run") else [exe]
    r = subprocess.run(runner, input="\n".join(cmds) + "\n", text=True, capture_output=True, cwd=AVLDIR, timeout=120)
    open(os.path.join(AVLDIR, f"{tag}.log"), "w").write(r.stdout + r.stderr)
    out = {}
    out.update(parse(os.path.join(AVLDIR, f"{tag}_ft.txt")))
    out.update(parse(os.path.join(AVLDIR, f"{tag}_st.txt")))
    if "CLa" not in out:
        raise RuntimeError(f"AVL produced no stability file for '{tag}'. Open results/avl/{tag}.log and check the command flow "
                           "(menu prompts differ slightly between AVL builds).")
    return out


def write_inputs(D, mp, fin_h, el, tw, name="beluga"):
    open(os.path.join(AVLDIR, name + ".avl"), "w").write(avl_text(D, mp, fin_h, el, tw))
    open(os.path.join(AVLDIR, name + ".mass"), "w").write(mass_text(mp, D))
    if D.get("airfoil_file") and os.path.exists(D["airfoil_file"]):
        shutil.copy(D["airfoil_file"], os.path.join(AVLDIR, "af.dat"))
    elif os.path.exists(os.path.join(C.RES, "best_airfoil.dat")):
        shutil.copy(os.path.join(C.RES, "best_airfoil.dat"), os.path.join(AVLDIR, "af.dat"))
    return name + ".avl"


def control_scale(avlfile, tag="cscale"):
    """AVL control derivatives are per radian OR per degree depending on build -> measure it by finite difference."""
    cms = []
    for dd in (+5.0, -5.0):
        r = avl_run(avlfile, ["a a 2.0", f"d1 d1 {dd}"], f"{tag}{int(dd)}")
        cms.append(r["Cmtot"])
    fd_per_deg = (cms[0] - cms[1]) / 10.0
    return fd_per_deg


# ------------------------------------------------------------------ main
def main():
    D = json.load(open(os.path.join(C.RES, "design.json")))
    mp = json.load(open(os.path.join(C.RES, "mass_props.json")))
    CLc = D["CL_cruise"]; CL_slow = 0.75 * D["CLmax_3d"]
    fin_h, el = D["fin"]["height"], D["elevon"]["chord_frac"]
    tw0 = D["washout_deg"]
    name = write_inputs(D, mp, fin_h, el, tw0)
    print(f"wrote {AVLDIR}/beluga.avl and beluga.mass  (CG x = {mp['cg'][0]*1000:.1f} mm, Sref {D['S']*1e4:.0f} cm^2)")
    if "--dry" in sys.argv:
        return
    # ---- stage B: AVL-trimmed washout
    print("\nStage B: trim washout with AVL (elevon deflection at cruise CL = %.2f)" % CLc)
    pts = []
    for tw in (tw0 - 2.0, tw0, tw0 + 2.0):
        write_inputs(D, mp, fin_h, el, tw)
        r = avl_run(name, [f"a c {CLc:.4f}", "d1 pm 0"], "twtrim")
        pts.append((tw, r.get("elevator", np.nan)))
        print(f"   twist {tw:+.2f} deg -> trim elevator {r.get('elevator', np.nan):+.2f} deg, alpha {r.get('Alpha', np.nan):+.2f}")
    p = np.polyfit([a for a, _ in pts], [b for _, b in pts], 1)
    tw_avl = float(-p[1] / p[0]) if abs(p[0]) > 1e-6 else tw0
    tw_avl = float(np.clip(tw_avl, -9, 1))
    print(f"   => AVL says washout {tw_avl:+.2f} deg gives zero elevon at cruise (VLM screen said {tw0:+.2f})")
    # ---- stage C: fin x elevon sweep
    print("\nStage C: fin height x elevon chord sweep")
    print("  fin[mm] elev[%]   Cnb    Clb   spiral  Cm_de   de_cruise  de_slow(CL%.2f)  SM_avl" % CL_slow)
    rows = []
    for h in C.FIN_HEIGHTS:
        for ef in C.ELEVON_CHORD_FRACS:
            write_inputs(D, mp, h, ef, tw_avl)
            rc = avl_run(name, [f"a c {CLc:.4f}", "d1 pm 0"], "sw_c")
            rs = avl_run(name, [f"a c {CL_slow:.4f}", "d1 pm 0"], "sw_s")
            sm = (rc.get("Xnp", np.nan) - mp["cg"][0]) / D["MAC"]
            spiral = (rc["Clb"] * rc["Cnr"]) / (rc["Clr"] * rc["Cnb"]) if rc["Clr"] * rc["Cnb"] != 0 else np.nan
            rows.append(dict(fin=h, el=ef, Cnb=rc["Cnb"], Clb=rc["Clb"], spiral=spiral, Cmd=rc.get("Cmd1", np.nan),
                             de_cruise=rc.get("elevator", np.nan), de_slow=rs.get("elevator", np.nan), SM=sm))
            r_ = rows[-1]
            print(f"  {h*1000:5.0f}  {ef*100:5.0f}   {r_['Cnb']:+.3f}  {r_['Clb']:+.3f}  {spiral:5.2f}  {r_['Cmd']:+.3f}   {r_['de_cruise']:+6.2f}    {r_['de_slow']:+7.2f}       {sm*100:5.1f}%")
    ok = [r for r in rows if r["Cnb"] >= C.CNB_MIN and abs(r["de_slow"]) <= C.DE_MAX_SLOW_DEG and abs(r["de_cruise"]) <= C.DE_MAX_CRUISE_DEG]
    pool = ok if ok else rows
    best = min(pool, key=lambda r: (r["fin"], r["el"]))       # smallest fin (least weight/drag) that passes, then smallest elevon
    print("\n  selected:", "OK (meets all limits)" if ok else "NO combination met all limits -> closest chosen, read the table",
          f"fin {best['fin']*1000:.0f} mm, elevon {best['el']*100:.0f}% chord")
    # ---- stage D: final
    write_inputs(D, mp, best["fin"], best["el"], tw_avl)
    final = avl_run(name, [f"a c {CLc:.4f}", "d1 pm 0"], "final")
    fd = control_scale(name)
    scale = fd * 57.29578 / final["Cmd1"] if final.get("Cmd1") else 1.0
    scale = 57.29578 if abs(scale - 57.3) < abs(scale - 1.0) else 1.0   # snap: derivs per rad (1) or per deg (57.3)
    print(f"\nfinal: Xnp = {final['Xnp']*1000:.1f} mm, CG = {mp['cg'][0]*1000:.1f} mm -> SM = {(final['Xnp']-mp['cg'][0])/D['MAC']*100:.1f}% MAC")
    print(f"control-derivative scale detected from finite difference: x{scale:.1f} to convert AVL Cmd1/Cld2 etc. to per-rad")
    res = dict(final=final, sweep=rows, selected=best, twist_deg=tw_avl, ctrl_scale_to_per_rad=scale, CL_cruise=CLc, CL_slow=CL_slow)
    json.dump(res, open(os.path.join(C.RES, "avl_results.json"), "w"), indent=1)
    D["washout_deg_avl"] = tw_avl; D["fin_final"] = best["fin"]; D["elevon_final"] = best["el"]
    json.dump(D, open(os.path.join(C.RES, "design.json"), "w"), indent=1)
    shutil.copy(os.path.join(AVLDIR, "final_st.txt"), os.path.join(AVLDIR, "final_st.txt"))
    print("saved results/avl_results.json -> run s06_state_space.py next")


if __name__ == "__main__":
    main()
